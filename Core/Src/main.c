/* Read All Sensors and Send Formatted Telemetry Line */
void Read_Sensors_And_Transmit(void) {
    uint8_t n_fields = 0;
    float temp = 0.0f, hum = 0.0f, pres = 0.0f, gas = 0.0f;
    uint8_t bme_valid = 0;

    // Read BME680 via wrapper
    if (g_bme_sensor_ready) {
        bme68x_set_op_mode(BME68X_FORCED_MODE, &bme_dev);
        uint32_t del_period = bme68x_get_meas_dur(BME68X_FORCED_MODE, &bme_conf, &bme_dev) + (bme_heatr_conf.heatr_dur * 1000);
        bme_dev.delay_us(del_period, bme_dev.intf_ptr);

        if (bme68x_get_data(BME68X_FORCED_MODE, &bme_data, &n_fields, &bme_dev) == BME68X_OK && n_fields > 0) {
            temp = bme_data.temperature;
            hum = bme_data.humidity;
            pres = bme_data.pressure / 100.0f;
            gas = bme_data.gas_resistance / 1000.0f;
            bme_valid = 1;
        }
    }

    // Read Wind Speed Sensor from ADC wrapper
    float wind_speed = Read_Wind_Speed(&hadc1);

    // Format Telemetry Line for Raspberry Pi Parser
    snprintf(g_telemetry_tx_buf, sizeof(g_telemetry_tx_buf),
             "BME_VALID:%d,TEMP:%.2f,HUM:%.2f,PRES:%.2f,GAS:%.2f,RAIN_LVL:%u,RAIN_ACT:%u,WIND_SPD:%.2f\r\n",
             bme_valid, temp, hum, pres, gas, rain_sensor.rain_level, rain_sensor.is_raining, wind_speed);

    // Transmit over USART2 (ST-Link USB to Pi)
    HAL_UART_Transmit(&huart2, (uint8_t *)g_telemetry_tx_buf, strlen(g_telemetry_tx_buf), 100);
}
